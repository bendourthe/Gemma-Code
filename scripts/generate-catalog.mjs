/**
 * Regenerate docs/index.md as a per-module summary catalog.
 *
 * Quick-orientation document for new contributors and AI agents: one row per
 * top-level src/ subdirectory listing file count, total LOC, the entry-point
 * hint, and the top exported symbols. Output is byte-deterministic with
 * respect to src/ contents; rerunning the script with no source changes
 * produces no diff.
 *
 * Inputs: src/<subdir>/**.ts
 * Output: docs/index.md
 *
 * Hand-written one-liners live in MODULE_DESCRIPTIONS below. CI runs
 * `npm run catalog:check` (regenerate then `git diff --exit-code`) so
 * out-of-sync rows fail the build.
 *
 * Run via: `npm run catalog`.
 */

