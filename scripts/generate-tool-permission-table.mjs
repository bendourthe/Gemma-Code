#!/usr/bin/env node
/**
 * Regenerate the tool-permission-tier table in docs/archive/versions/v0/v0.5.0/architecture.md
 * directly from src/guardrails/PermissionTiers.ts so the doc cannot drift
 * out of sync. Replaces the block delimited by the markers
 *   <!-- BEGIN:TOOL-PERMISSION-TABLE -->
 *   <!-- END:TOOL-PERMISSION-TABLE -->
 *
 * Run via:
 *   npm run perm-tier             (regenerate in place)
 *   npm run perm-tier:check       (fail when out of sync; used in CI)
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const sourcePath = path.join(repoRoot, "src/guardrails/PermissionTiers.ts");
const docPath = path.join(repoRoot, "docs/archive/versions/v0/v0.5.0/architecture.md");
const beginMarker = "<!-- BEGIN:TOOL-PERMISSION-TABLE -->";
const endMarker = "<!-- END:TOOL-PERMISSION-TABLE -->";

const tierLabels = {
  0: { label: "0 -- auto", behavior: "Run silently" },
  1: { label: "1 -- confirm", behavior: "One-click confirmation" },
  2: {
    label: "2 -- dangerous",
    behavior: "Blocking confirmation; `editMode: plan` shows a diff",
  },
};
const tierEnumToNumber = {
  AUTO_APPROVE: 0,
  CONFIRM: 1,
  DANGEROUS: 2,
};

function parseToolMap(source) {
  const start = source.indexOf("TOOL_PERMISSION_MAP");
  if (start < 0) {
    throw new Error("TOOL_PERMISSION_MAP not found in PermissionTiers.ts");
  }
  const open = source.indexOf("{", start);
  const close = source.indexOf("};", open);
  if (open < 0 || close < 0) {
    throw new Error("Failed to locate TOOL_PERMISSION_MAP body");
  }
  const body = source.slice(open + 1, close);
  const entries = [];
  const re = /([a-z_]+):\s*PermissionTier\.([A-Z_]+)/g;
  let match;
  while ((match = re.exec(body)) !== null) {
    const tier = tierEnumToNumber[match[2]];
    if (tier === undefined) {
      throw new Error(`Unknown PermissionTier: ${match[2]}`);
    }
    entries.push({ name: match[1], tier });
  }
  if (entries.length === 0) {
    throw new Error("No tool entries parsed from TOOL_PERMISSION_MAP");
  }
  return entries;
}

function renderTable(entries) {
  const byTier = new Map();
  for (const e of entries) {
    if (!byTier.has(e.tier)) byTier.set(e.tier, []);
    byTier.get(e.tier).push(e.name);
  }
  const lines = [
    "| Tier | Tools | Default behavior |",
    "|------|-------|-------------------|",
  ];
  for (const tier of [0, 1, 2]) {
    const tools = (byTier.get(tier) ?? []).sort();
    const meta = tierLabels[tier];
    const toolList = tools.length > 0
      ? tools.map((t) => `\`${t}\``).join(", ")
      : "(none)";
    lines.push(`| ${meta.label} | ${toolList} | ${meta.behavior} |`);
  }
  return lines.join("\n");
}

function regenerate(check) {
  const source = fs.readFileSync(sourcePath, "utf8");
  const entries = parseToolMap(source);
  const table = renderTable(entries);

  // v0.9.0 Phase 1: normalise CRLF -> LF up-front. Git's `core.autocrlf=true`
  // setting (default on Windows installs) checks LF-committed docs out with
  // CRLF endings; without this normalisation the LF block we generate below
  // is "out of sync" by line endings alone on Windows.
  const doc = fs.readFileSync(docPath, "utf8").replace(/\r\n/g, "\n");
  const beginIdx = doc.indexOf(beginMarker);
  const endIdx = doc.indexOf(endMarker);
  if (beginIdx < 0 || endIdx < 0 || endIdx < beginIdx) {
    throw new Error(
      `Markers not found in ${docPath}. Expected ${beginMarker} and ${endMarker}.`,
    );
  }

  const before = doc.slice(0, beginIdx + beginMarker.length);
  const after = doc.slice(endIdx);
  const generatedNote =
    "<!-- Generated by scripts/generate-tool-permission-table.mjs from src/guardrails/PermissionTiers.ts. Do not edit manually. -->";
  const block = `${before}\n${generatedNote}\n\n${table}\n\n${after}`;

  if (check) {
    if (block !== doc) {
      process.stderr.write(
        "[generate-tool-permission-table] Doc is out of sync with PermissionTiers.ts. Run `npm run perm-tier` and commit the result.\n",
      );
      process.exit(1);
    }
    return;
  }

  if (block !== doc) {
    fs.writeFileSync(docPath, block, "utf8");
    process.stdout.write(`[generate-tool-permission-table] Updated ${path.relative(repoRoot, docPath)}\n`);
  } else {
    process.stdout.write("[generate-tool-permission-table] No changes\n");
  }
}

const check = process.argv.includes("--check");
regenerate(check);
